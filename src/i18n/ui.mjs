export function t(lang, key, vars = {}) {
  const table = UI[lang] || UI.en;
  let s = table[key] ?? UI.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hasUI(lang) {
  return Boolean(UI[lang]);
}
